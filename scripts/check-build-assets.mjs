#!/usr/bin/env node
/**
 * Assert that a production build actually produced the runtime assets it needs.
 *
 * ## Why this exists
 *
 * `public/maplibre-gl-worker.mjs` and `public/maplibre-gl-shared.mjs` are
 * **generated**, not committed: `scripts/sync-maplibre-worker.mjs` copies them
 * out of `node_modules` at `prebuild`, and `.gitignore` excludes them so a stale
 * hand-copied worker cannot drift from the installed maplibre-gl.
 *
 * That arrangement has exactly one failure mode, and it shipped: a deployment
 * whose build command is `next build` rather than `npm run build` never runs
 * `prebuild`, so the worker is never copied — and because it is gitignored, it is
 * not in the checkout either. The map then renders raster basemap tiles (which
 * need no worker) while every GeoJSON source stays silently empty. The page looks
 * alive and carries no data, which is the worst possible way for this to fail.
 *
 * So the check runs as `postbuild`: any build, on any machine, by any command
 * that goes through `npm run build`, fails loudly if the asset is missing. It
 * also compares bytes against `node_modules`, because a worker from a different
 * maplibre-gl version is a subtler version of the same bug.
 *
 * Nothing here touches the network.
 */

import { existsSync, readFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Files the browser must be able to fetch, and where they come from. */
export const REQUIRED_RUNTIME_ASSETS = [
  'maplibre-gl-worker.mjs',
  'maplibre-gl-shared.mjs',
]

const problems = []

for (const file of REQUIRED_RUNTIME_ASSETS) {
  const served = join(root, 'public', file)
  const source = join(root, 'node_modules', 'maplibre-gl', 'dist', file)

  if (!existsSync(served)) {
    problems.push(
      `public/${file} is missing. It is generated by scripts/sync-maplibre-worker.mjs at ` +
        'prebuild and is gitignored, so a build command that bypasses `npm run build` ' +
        'produces a deployment whose map silently carries no data.',
    )
    continue
  }
  if (statSync(served).size === 0) {
    problems.push(`public/${file} exists but is empty.`)
    continue
  }
  if (!existsSync(source)) {
    problems.push(
      `node_modules/maplibre-gl/dist/${file} is missing, so the served copy cannot be verified.`,
    )
    continue
  }
  if (!readFileSync(served).equals(readFileSync(source))) {
    problems.push(
      `public/${file} differs from node_modules/maplibre-gl/dist/${file}. The served worker is ` +
        'from a different maplibre-gl version than the one bundled with the page.',
    )
  }
}

if (problems.length > 0) {
  process.stderr.write('build asset check FAILED\n\n')
  for (const problem of problems) process.stderr.write(`  - ${problem}\n`)
  process.stderr.write(
    '\nRun `npm run build` (not `next build`) so the prebuild step runs.\n',
  )
  process.exit(1)
}

process.stdout.write(
  `build assets present and matching node_modules (${REQUIRED_RUNTIME_ASSETS.join(', ')})\n`,
)
